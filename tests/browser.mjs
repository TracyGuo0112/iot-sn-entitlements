import assert from 'node:assert/strict';
import { mkdir, readFile } from 'node:fs/promises';
import { customers, queryDevices, getBatchSummary } from '../dist/data.mjs';

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless:true, ...(process.env.PLAYWRIGHT_EXECUTABLE_PATH ? { executablePath:process.env.PLAYWRIGHT_EXECUTABLE_PATH } : {}) });
const page = await browser.newPage({ viewport:{ width:1440,height:1000 },locale:'zh-CN' });
const errors = [];
const checks = [];
page.on('pageerror', error => errors.push(error.message));
await mkdir('artifacts', { recursive:true });
const check = (name, condition) => { assert.ok(condition,name); checks.push(name); };
const rows = () => page.locator('.results-panel tbody tr');
const query = async text => { await page.locator('#query').fill(text); await page.locator('#query-form').evaluate(form => form.requestSubmit()); };
const close = async () => { await page.keyboard.press('Escape'); await page.locator('[role="dialog"]').waitFor({state:'detached'}); };

try {
  await page.goto(process.env.DEMO_URL || 'http://127.0.0.1:4173',{waitUntil:'networkidle'});
  check('initial device list has 10 paginated records', await rows().count() === 10);
  await page.locator('[data-pagination="2"]').first().click();
  check('pagination changes the first SN', !(await rows().first().innerText()).includes('XMSN202600001'));
  await page.locator('[data-stat="restored"]').click();
  check('summary card filters restored devices', await rows().count() === 1 && (await rows().first().innerText()).includes('待重领'));
  await page.locator('[data-action="reset-filters"]').first().click();
  await query('XMSN202600004');
  await page.locator('tbody [data-device]').first().click();
  check('SN detail shows restored eligibility and history', (await page.locator('[role="dialog"]').innerText()).includes('当前可领取次数') && (await page.locator('[role="dialog"]').innerText()).includes('退权益成功，恢复一次领取资格'));
  await page.screenshot({path:'artifacts/sn-detail.png',fullPage:true});
  await close();
  await page.locator('[data-action="reset-filters"]').first().click();
  await page.locator('[data-query-mode="batch"]').click();
  const uploadCsv = async text => { await page.locator('#sn-file').setInputFiles({name:'SN清单.csv',mimeType:'text/csv',buffer:Buffer.from(text)}); await page.waitForFunction(() => document.querySelector('.upload-title')?.textContent !== '正在读取表格…'); };
  await uploadCsv('SN\nXMSN202600001\nXMSN202600004\nUNKNOWN');
  check('uploaded CSV queries only complete matching SNs', await rows().count() === 2);
  check('unmatched uploaded SNs are visible', (await page.locator('.unmatched-note').innerText()).includes('UNKNOWN'));
  await uploadCsv('SN\n202600001');
  check('single token from a spreadsheet remains exact', await rows().count() === 0);
  await uploadCsv('SN\nXMSN202600001\n\nXMSN202600001\nXMSN202600004');
  check('upload reports duplicate SNs and blank lines', (await page.locator('.upload-summary').innerText()).includes('已去重 1 条'));
  await uploadCsv('SN\n=1+2');
  check('invalid rows block the query and show their location', await rows().count() === 0 && (await page.locator('.upload-status').innerText()).includes('第 2 行'));
  await uploadCsv('设备\nXMSN202600001');
  check('a missing SN header gives a useful error', await page.locator('.upload-status').isVisible());
  await uploadCsv('SN\n\n');
  check('an empty template prompts users to fill the SN column', (await page.locator('.upload-status').innerText()).includes('没有可查询的 SN'));
  await page.locator('#sn-file').setInputFiles('dist/templates/sn-query-template.xlsx');
  await page.waitForFunction(() => document.querySelector('.upload-title')?.textContent === '表格已读取，查询完成');
  check('provided Excel template uploads and returns three SNs', await rows().count() === 3);
  const templateDownloadEvent = page.waitForEvent('download');
  await page.locator('a[download="IOT-SN批量查询模板.xlsx"]').click();
  const templateDownload = await templateDownloadEvent;
  check('Excel template downloads as a real XLSX archive', (await readFile(await templateDownload.path())).subarray(0,2).toString() === 'PK');
  await page.screenshot({path:'artifacts/batch-upload.png',fullPage:true,animations:'disabled'});
  await page.locator('[data-query-mode="single"]').click();
  await query('XMSN202600001');
  check('first tenant shared SN is unclaimed', (await rows().first().innerText()).includes('待领取'));
  const downloadEvent = page.waitForEvent('download');
  await page.locator('[data-action="export"]').click();
  const download = await downloadEvent;
  const csv = await readFile(await download.path(),'utf8');
  check('CSV export follows filters and contains Chinese headers', csv.includes('SN 设备号') && csv.includes('XMSN202600001') && !csv.includes('XMSN202600002'));

  await page.locator('[data-action="switch-key"]').click();
  await page.locator('#appkey').fill('unknown-appkey');
  await page.locator('#key-form').evaluate(form => form.requestSubmit());
  check('unknown appkey shows validation error', await page.locator('#key-error').isVisible());
  check('unknown appkey does not change the active tenant', (await page.locator('.context-info').innerText()).includes(customers[0].name));
  await page.locator('#appkey').fill(customers[1].appkey);
  await page.locator('#key-form').evaluate(form => form.requestSubmit());
  check('switching appkey clears old query and displays new customer', await page.locator('#query').inputValue() === '' && (await page.locator('.context-info').innerText()).includes(customers[1].name));
  await query('XMSN202600001');
  check('shared SN has its independent second tenant state', (await rows().first().innerText()).includes('已领取'));
  await page.locator('[data-action="reset-filters"]').first().click();
  await page.locator('#from').fill('2026-10-15');
  await page.locator('#to').fill('2026-09-01');
  await page.locator('#query-form').evaluate(form => form.requestSubmit());
  check('reversed date range is rejected', await page.locator('#query-error').isVisible());

  await page.locator('.sidebar [data-page="batches"]').click();
  check('import history displays three tenant batches', await rows().count() === 3);
  const id = await page.locator('tbody [data-batch]').first().getAttribute('data-batch');
  await page.locator('tbody [data-batch]').first().click();
  const summary = getBatchSummary(id,customers[1].id);
  check('batch snapshot totals reconcile with displayed rows', await page.locator('[role="dialog"] tbody tr').count() === summary.total);
  await page.locator('[data-batch-filter="failed"]').click();
  check('batch result filter shows only failed records', await page.locator('[role="dialog"] tbody tr').count() === summary.failed && (await page.locator('[role="dialog"] tbody').innerText()).includes('处理失败'));
  const batchDownloadEvent = page.waitForEvent('download');
  await page.locator('[data-action="export-batch"]').click();
  const batchDownload = await batchDownloadEvent;
  const batchCsv = await readFile(await batchDownload.path(),'utf8');
  check('batch export follows the result filter', batchCsv.includes('处理失败') && !batchCsv.includes('新增成功'));
  await page.screenshot({path:'artifacts/import-detail.png',fullPage:true});
  await close();
  await query('XMSN202600004');
  check('batch search accepts an SN and finds related historical batches', await rows().count() === 2);

  await page.locator('.sidebar [data-page="orders"]').click();
  await page.locator('select[name="refundStatus"]').selectOption('success');
  await page.locator('#query-form').evaluate(form => form.requestSubmit());
  check('order refund filter is independent and returns funded refund', await rows().count() > 0 && (await rows().first().innerText()).includes('退款成功'));
  await page.locator('tbody [data-order]').first().click();
  check('order detail distinguishes monetary refund from entitlement', (await page.locator('[role="dialog"]').innerText()).includes('本页退款状态表示资金退款'));
  await close();
  await page.locator('.sidebar .nav-item[data-page="guide"]').click();
  check('guide documents the three import branches', (await page.locator('.rule-flow').innerText()).includes('退权益并恢复资格'));
  await page.locator('.sidebar .nav-item[data-page="devices"]').click();
  await page.locator('[data-action="reset-filters"]').first().click();
  check('tenant device total remains consistent after navigation', queryDevices({tenantId:customers[1].id}).length === 25);
  await page.screenshot({path:'artifacts/desktop.png',fullPage:true});
  check('desktop layout has no page overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'artifacts/mobile.png',fullPage:true});
  check('mobile layout keeps overflow inside the tables', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.locator('[data-action="switch-key"]').click();
  check('appkey dialog fits mobile width', await page.locator('.modal').evaluate(el => el.getBoundingClientRect().right <= innerWidth));
  await close();
  await page.locator('[data-query-mode="batch"]').click();
  check('batch upload panel fits mobile width', await page.locator('.upload-zone').evaluate(el => el.getBoundingClientRect().right <= innerWidth));
  check('no unhandled browser exceptions', errors.length === 0);
  console.log(JSON.stringify({passed:checks.length,checks,errors},null,2));
} finally { await browser.close(); }
